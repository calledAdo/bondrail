// Regenerates src/abis.ts from the Foundry build of the protocol (contracts/out). Run after `forge build`.
import fs from 'node:fs';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname);
const out = path.resolve(here, '../../../contracts/out');
const contracts = ['SliceFactory', 'SliceAccount', 'SliceBond', 'SliceCovenant', 'SliceEarner'];
let body = '// Generated by scripts/generate-abis.ts from contracts/out. Do not edit by hand.\n';
for (const name of contracts) {
  const abi = JSON.parse(fs.readFileSync(path.join(out, `${name}.sol`, `${name}.json`), 'utf8')).abi;
  const id = name[0].toLowerCase() + name.slice(1) + 'Abi';
  body += `export const ${id} = ${JSON.stringify(abi)} as const;\n`;
}
fs.writeFileSync(path.resolve(here, '../src/abis.ts'), body);
console.log(`abis.ts: ${contracts.join(', ')}`);
