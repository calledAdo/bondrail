// Writes config.yaml from docs/deployments/<chainId>.json (written by scripts/deploy.ts).
//   node gen-config.mjs 31337          local anvil (RPC http://127.0.0.1:8545)
//   node gen-config.mjs 10143          Monad testnet (HyperSync by default; MONAD_RPC opts into RPC)
// HyperSync is the default on supported chains, including Monad testnet (10143).
// Envio Cloud provides managed HyperSync access; no rpc: block or personal ENVIO_API_TOKEN is needed.
// Routers, bonds and launchpads are created by the factory, so they are registered dynamically
// from factory events; only the factory, covenant and USDC have fixed addresses.
import fs from 'node:fs';
import path from 'node:path';
import { deploymentName, deploymentPath, assertWritable } from '../scripts/deployment-path.mjs';

const [chainId = '10143'] = process.argv.slice(2);
const here = path.dirname(new URL(import.meta.url).pathname);
const name = deploymentName();
const manifest = deploymentPath(path.resolve(here, '..'), chainId, name);
const dep = JSON.parse(fs.readFileSync(manifest, 'utf8'));
if (String(dep.chainId) !== chainId || (dep.deployment ?? 'main') !== name) throw new Error('Deployment identity mismatch');
const startBlock = dep.startBlock ?? 0;
// Production Envio stays on its existing envio-next release branch; generation here is local only.
const output = path.resolve(process.env.BONDRAIL_INDEXER_DIR ?? here);
for (const file of ['config.yaml', 'src/deployment.ts']) assertWritable(path.join(output, file));
fs.mkdirSync(path.join(output, 'src'), { recursive: true });
const rpc =
  chainId === '31337'
    ? `\n    rpc: ${JSON.stringify(process.env.BONDRAIL_RPC_URL ?? 'http://127.0.0.1:8545')}`
    : !process.env.MONAD_RPC // default: HyperSync (Envio Cloud); MONAD_RPC=<url> syncs from an RPC instead
      ? ''
      : `\n    rpc:\n      - url: ${process.env.MONAD_RPC}\n        for: sync\n        # Monad's public RPC caps eth_getLogs at 100 blocks.\n        initial_block_interval: 100\n        interval_ceiling: 100`;
// Optional explicit address; no deployment manifest is modified or assumed.
const creditRegistry = process.env.CREDIT_REGISTRY_ADDRESS || dep.creditRegistry;
if (creditRegistry && (!/^0x[0-9a-fA-F]{40}$/.test(creditRegistry) || /^0x0{40}$/.test(creditRegistry)))
  throw new Error('Invalid CREDIT_REGISTRY_ADDRESS');
const tx = '\n        field_selection: { transaction_fields: [hash] }';

fs.writeFileSync(
  path.join(output, 'config.yaml'),
  `# yaml-language-server: $schema=./node_modules/envio/evm.schema.json
# Generated by gen-config.mjs from ${path.basename(manifest)}. Do not edit by hand.
name: bondrail${name === 'main' ? '' : `-${name}`}
description: Bondrail revenue bonds on Monad
contracts:
  - name: BondrailFactory
    events:
      - event: "AccountCreated(address indexed issuer, address indexed account, address indexed asset)"
      - event: "NativeApproval(address indexed project, bool approved)"
      - event: "NativeTemplate(bytes32 indexed initCodeHash, bool approved)"
      - event: "NativeDeployed(address indexed account, address indexed project, bytes32 indexed initCodeHash)"
      - event: "BondCreated(address indexed issuer, address indexed account, address indexed bond, uint8 adapter, bytes32 policyHash, bytes32 termsHash)"${tx}
      - event: "SecondReleaseApproved(address indexed bond, uint8 mode, uint256 eligibleRevenue)"${tx}
  - name: BondrailAccount
    events:
      - event: "Revenue(address indexed bond, address indexed payer, uint256 amount, uint256 toBond, uint256 toIssuer, bool collected)"${tx}
      - event: "Settled(address indexed payer, uint256 value, bytes32 indexed nonce)"${tx}
      - event: "Collected(address indexed payer, uint256 gross, uint256 fee, bool outgoing)"
      - event: "ProjectBound(address indexed project)"
      - event: "Attached(address indexed bond)"
      - event: "Detached(address indexed bond)"
  - name: BondrailBond
    events:
      - event: "Deposited(address indexed payer, uint256 amount, uint256 funded)"${tx}
      - event: "Withdrawn(address indexed holder, address indexed receiver, uint256 amount, uint256 funded)"${tx}
      - event: "Activated(address indexed issuer, uint256 released, uint256 undrawn, uint256 effectiveCap)"${tx}
      - event: "PrincipalReleased(uint256 amount, uint256 releasedTotal, uint256 effectiveCap, bytes32 evidenceHash)"${tx}
      - event: "UndrawnRecovered(uint256 amount, uint256 recoveryTotal)"${tx}
      - event: "RevenueReceived(uint256 amount, uint256 totalRevenue, uint256 pool)"${tx}
      - event: "TriggerChanged(bool triggered)"${tx}
      - event: "DefaultRecorded(bytes32 indexed evidenceHash, uint256 stakeRecovered)"${tx}
      - event: "CollectionClosed(uint8 reason, uint64 closedAt, uint64 settleAfter, uint256 pool)"${tx}
      - event: "SettlementFinalized(uint256 pool, uint256 supply, uint256 issuerStakeCredit)"${tx}
      - event: "FundingCancelled(uint256 refundable, uint256 issuerStakeCredit)"${tx}
      - event: "Refunded(address indexed holder, address indexed receiver, uint256 amount)"${tx}
      - event: "Redeemed(address indexed holder, address indexed receiver, uint256 tokens, uint256 amount)"${tx}
      - event: "Transfer(address indexed from, address indexed to, uint256 value)"
  - name: BondrailCovenant
    events:
      - event: "ObservationAccepted(address indexed bond, uint64 indexed epoch, uint8 result, uint64 observedAt, bytes32 evidenceHash, bytes32 digest)"${tx}
      - event: "CovenantDefault(address indexed bond, uint64 firstEpoch, uint64 secondEpoch, bytes32 evidenceHash)"${tx}
  - name: BondrailCreditRegistry
    events:
      - event: "BondRecorded(address indexed account, address indexed bond)"${tx}
      - event: "Attested(address indexed account, address indexed signer, uint256 chainId, uint64 periodStart, uint64 periodEnd, uint256 attributedRevenue, uint256 excludedRevenue, uint256 distinctPayers, uint16 topPayerShareBps, uint256 creditLine, bytes32 evidenceHash, uint64 issuedAt, uint64 expiresAt, uint256 nonce)"${tx}
  - name: USDC
    events:
      - event: "Transfer(address indexed from, address indexed to, uint256 value)"
        field_selection: { transaction_fields: [hash, to] }
      - event: "AuthorizationUsed(address indexed authorizer, bytes32 indexed nonce)"${tx}
chains:
  - id: ${chainId}
    start_block: ${startBlock}${rpc}
    contracts:
      - name: BondrailFactory
        address: "${dep.factory}"
      - name: BondrailCovenant
        address: "${dep.covenant}"
      - name: USDC
        address: "${dep.asset}"
      # Registry from the selected manifest, or an explicit address override.
      - name: BondrailCreditRegistry${creditRegistry ? `\n        address: "${creditRegistry}"` : ''}
      - name: BondrailAccount
      - name: BondrailBond
`,
);
fs.writeFileSync(
  path.join(output, 'src/deployment.ts'),
  `// Generated by gen-config.mjs. Do not edit.\nexport const FACTORY = '${dep.factory.toLowerCase()}';\n` +
    `// Keep simulated test blocks aligned with config.yaml after regeneration.\n` +
    `export const START_BLOCK = ${startBlock};\n` +
    `// The asset whose Transfers are indexed (x402 settles in it); accounts in other assets are seen via their events.\n` +
    `export const INDEXED_ASSET = '${dep.asset.toLowerCase()}';\n`,
);
console.log(`config.yaml for chain ${chainId} from block ${startBlock}`);
